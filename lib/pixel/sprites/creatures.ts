function withLegs(body: Frame, legs: Frame, lift = 0): Frame {
  const rows = [...shift(body, 0, -lift)];
  rows[14] = legs[0];
  rows[15] = legs[1];
  return rows;
}

const BLINK = { 6: '...kxzxxxxzxk...' } as const;
function blink(rows: Frame): Frame {
  return rows.map((row, y) => (y === 6 ? BLINK[6] : row));
}

