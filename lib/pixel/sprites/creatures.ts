/** Turns a standing frame on its side for sleeping. */
function lieDown(rows: Frame): Frame {
  const size = rows.length;
  const out: string[] = [];
  for (let y = 0; y < size; y++) {
    let row = '';
    for (let x = 0; x < size; x++) row += rows[size - 1 - x][y];
    out.push(row);
  }
  return shift(out, 0, 2);
}

/** Every opaque pixel white: a one-frame hit flash. */
export function silhouette(rows: Frame, char = 'L'): Frame {
  return rows.map((row) => row.replace(/[^.]/g, char));
}

const RAGE: Record<string, string> = { x: 'e', Z: 'R', z: 'r' };
/** Iron helm in place of the hood when a dwarf wears armor. */
const HELM: Record<string, string> = { 7: 'v', 8: 'V', 9: 'i' };
function helmet(rows: Frame): Frame {
  return rows.map((row, y) => (y >= 1 && y <= 4 ? recolor([row], HELM)[0] : row));
}

const stand = withLegs(DWARF_BODY, LEGS.stand);
const walkA = withLegs(DWARF_BODY, LEGS.stepLeft, 1);
const walkB = withLegs(DWARF_BODY, LEGS.stepRight, 1);
const kneel = shift(withLegs(DWARF_BODY, ['................', '................']), 0, 2);

const DWARF_ANIMS = ['idle', 'walk', 'mine', 'fight', 'drink', 'pray', 'sleep', 'rage', 'armed', 'armed_walk'] as const;

function dwarfSet<P extends string>(prefix: P, dress: (rows: Frame) => Frame) {
  const d = (rows: Frame) => dress(rows);
  const rage = recolor(stand, RAGE);
  const sets: Record<(typeof DWARF_ANIMS)[number], SpriteDef> = {
    idle: sprite(16, 16, [d(stand), d(stand), d(stand), d(blink(stand))], 420),
    walk: sprite(16, 16, [d(walkA), d(stand), d(walkB), d(stand)], 130),
    mine: sprite(16, 16, [d(overlay(stand, PICK_UP)), d(overlay(stand, PICK_MID)), d(overlay(stand, PICK_DOWN))], 160),
    fight: sprite(16, 16, [d(overlay(stand, AXE_UP)), d(overlay(walkA, AXE_SWING))], 180),
    drink: sprite(16, 16, [d(stand), d(overlay(stand, MUG))], 380),
    pray: sprite(16, 16, [d(overlay(kneel, PRAY_HANDS)), d(overlay(shift(kneel, 0, -1), PRAY_HANDS))], 520),
    sleep: sprite(16, 16, [d(lieDown(blink(stand)))]),
    rage: sprite(16, 16, [d(rage), d(shift(rage, 1, 0)), d(rage), d(shift(rage, -1, 0))], 90),
    armed: sprite(16, 16, [d(overlay(stand, AXE_SIDE)), d(overlay(stand, AXE_SIDE)), d(overlay(blink(stand), AXE_SIDE))], 500),
    armed_walk: sprite(16, 16, [d(overlay(walkA, AXE_SIDE)), d(overlay(stand, AXE_SIDE)), d(overlay(walkB, AXE_SIDE)), d(overlay(stand, AXE_SIDE))], 130),
  };
  return Object.fromEntries(DWARF_ANIMS.map((anim) => [`${prefix}_${anim}`, sets[anim]])) as Record<`${P}_${(typeof DWARF_ANIMS)[number]}`, SpriteDef>;
}

